class ProfessionExtractorDebug(ImprovedProfessionExtractor):
    """Versione con debug output per profession extraction"""

    def extract_professions_debug(self, document_text: str, keywords: List[str],
                                  themes: List[str], category: str,
                                  top_k: int = 3, threshold: float = 0.55
                                 ) -> Tuple[List[str], Dict]:
        """Versione con trace completo della selezione"""

        debug_info = {
            'input': {
                'category': category,
                'top_keywords': keywords[:8],
                'themes': themes[:3]
            },
            'config': {
                'top_k': top_k,
                'threshold': threshold,
                'blacklist': list(self.blacklist)
            }
        }

        # CHECK: documenti normativi/informativi generici
        if category in ["Normativa e adempimenti", "Altro"]:
            debug_info['skip_reason'] = f'Categoria "{category}" indica documento generico/normativo'
            debug_info['final_professions'] = ['Nessuna (documento generico)']
            return [], debug_info

        doc_desc = f"""Settore: {category}.
Parole chiave: {', '.join(keywords[:8])}.
Temi: {', '.join(themes[:3])}.
Contenuto: {document_text[:1500]}"""

        # Compute similarities
        doc_emb = self.embedding_model.encode([doc_desc])
        similarities = cosine_similarity(doc_emb, self.profession_embeddings)[0]

        ranked = sorted(
            zip(self.known_professions, similarities),
            key=lambda x: x[1],
            reverse=True
        )

        # Top 10 for analysis
        debug_info['top10_raw'] = [
            {'profession': prof, 'similarity': round(float(score), 3)}
            for prof, score in ranked[:10]
        ]

        # Filter process
        selected = []
        blacklisted = []
        below_threshold = []

        for prof, score in ranked:
            if prof in self.blacklist:
                blacklisted.append({
                    'profession': prof,
                    'similarity': round(float(score), 3),
                    'reason': 'in blacklist'
                })
                continue

            if score >= threshold:
                selected.append(prof)
                if len(selected) >= top_k:
                    break
            else:
                below_threshold.append({
                    'profession': prof,
                    'similarity': round(float(score), 3),
                    'reason': f'below threshold ({threshold})'
                })

        debug_info['filtering'] = {
            'blacklisted': blacklisted[:5],  # Top 5 blacklisted
            'below_threshold': below_threshold[:5],  # Top 5 below threshold
            'selected': [
                {'profession': prof, 'rank': i+1}
                for i, prof in enumerate(selected)
            ]
        }

        # FALLBACK MIGLIORATO: check se best score è troppo basso
        if not selected:
            best_non_blacklisted = None
            best_score = 0

            for prof, score in ranked:
                if prof not in self.blacklist:
                    best_non_blacklisted = prof
                    best_score = score
                    break

            # Se il migliore è sotto 0.45, è un documento generico
            if best_score < 0.45:
                debug_info['fallback'] = {
                    'applied': True,
                    'reason': f'best_score ({best_score:.3f}) < 0.45 - documento generico',
                    'decision': 'Nessuna professione specifica (documento informativo/normativo)',
                    'best_candidate': best_non_blacklisted,
                    'best_score': round(float(best_score), 3)
                }
                selected = []  # Lista vuota per documenti generici
            else:
                # Fallback normale (0.40 < score < 0.55)
                selected = [best_non_blacklisted]
                debug_info['fallback'] = {
                    'applied': True,
                    'profession': best_non_blacklisted,
                    'similarity': round(float(best_score), 3),
                    'reason': 'no profession above threshold, using best non-blacklisted (weak match)'
                }

        debug_info['final_professions'] = selected if selected else ['Nessuna (documento generico)']

        return selected, debug_info


