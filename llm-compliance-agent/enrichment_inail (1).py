class CategoryClassifierDebug(DomainAwareCategoryClassifier):
    """Versione con debug output per category classification"""

    def classify_debug(self, keywords: List[str], themes: List[str],
                      laws: List[str]) -> Tuple[str, Dict]:
        """Versione con trace completo dello scoring"""

        debug_info = {
            'input': {
                'keywords': keywords,
                'themes': themes,
                'laws': laws
            }
        }

        all_text = ' '.join(keywords + themes).lower()

        # LIVELLO 1: Domain term scoring
        domain_scores = {}
        domain_details = {}

        for category, terms in self.category_terms.items():
            matches = sum(1 for term in terms if term in all_text)
            score = matches / max(len(terms), 1)
            domain_scores[category] = score
            domain_details[category] = {
                'score': round(score, 3),
                'matches': matches,
                'total_terms': len(terms),
                'matched_terms': [term for term in terms if term in all_text]
            }

        # Generic overlap for categories without specific terms
        for category in self.valid_categories:
            if category not in domain_scores:
                cat_words = set(category.lower().split())
                text_words = set(all_text.split())
                overlap = len(cat_words & text_words)
                score = overlap / max(len(cat_words), 1)
                domain_scores[category] = score
                domain_details[category] = {
                    'score': round(score, 3),
                    'strategy': 'generic_overlap',
                    'overlap': overlap
                }

        debug_info['domain_scoring'] = domain_details

        # Penalize "Normativa"
        if "Normativa e adempimenti" in domain_scores:
            specific_categories = [cat for cat in domain_scores.keys()
                                  if cat != "Normativa e adempimenti"]
            max_specific_score = max([domain_scores[cat] for cat in specific_categories], default=0)

            if max_specific_score > 0.15:
                original_score = domain_scores["Normativa e adempimenti"]
                domain_scores["Normativa e adempimenti"] *= 0.3
                debug_info['normativa_penalty'] = {
                    'applied': True,
                    'original_score': round(original_score, 3),
                    'penalized_score': round(domain_scores["Normativa e adempimenti"], 3),
                    'reason': f'max_specific_score={max_specific_score:.3f} > 0.15'
                }

        # Top 5 candidates
        top_candidates = sorted(domain_scores.items(), key=lambda x: x[1], reverse=True)[:5]
        debug_info['top5_candidates'] = [
            {'category': cat, 'domain_score': round(score, 3)}
            for cat, score in top_candidates
        ]

        # LIVELLO 2: Semantic similarity
        description = f"""Keywords: {', '.join(keywords[:10])}.
Temi: {', '.join(themes[:3])}.
Leggi: {', '.join(laws[:3]) if laws else 'Generiche'}."""

        desc_emb = self.embedding_model.encode([description])

        semantic_scores = []
        best_category = None
        best_score = 0

        for category, domain_score in top_candidates:
            cat_idx = self.valid_categories.index(category)
            sem_score = float(cosine_similarity(desc_emb, [self.category_embeddings[cat_idx]])[0][0])

            # Blending: 70% domain + 30% semantic
            combined_score = 0.7 * domain_score + 0.3 * sem_score

            semantic_scores.append({
                'category': category,
                'domain_score': round(domain_score, 3),
                'semantic_score': round(sem_score, 3),
                'combined_score': round(combined_score, 3),
                'blending': '0.7*domain + 0.3*semantic'
            })

            if combined_score > best_score:
                best_score = combined_score
                best_category = category

        debug_info['semantic_scoring'] = semantic_scores
        debug_info['best_match'] = {
            'category': best_category,
            'final_score': round(best_score, 3),
            'threshold': Config.CATEGORY_THRESHOLD
        }

        # Fallback check
        if best_score < Config.CATEGORY_THRESHOLD:
            debug_info['fallback'] = {
                'applied': True,
                'reason': f'best_score ({best_score:.3f}) < threshold ({Config.CATEGORY_THRESHOLD})',
                'final_category': 'Altro'
            }
            return "Altro", debug_info

        debug_info['final_category'] = best_category
        return best_category, debug_info


