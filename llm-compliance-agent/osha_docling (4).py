def get_osha_publication_links_with_range(
    search_url: str,
    start_page: int = 0,
    end_page: int = 4,
    max_pages: Optional[int] = None
) -> List[Dict[str, str]]:

    # Estrae link pubblicazioni OSHA con range di pagine - FIX: No break <5, continua fino end_page

    publications = []
    seen_urls = set()

    print(f"\n{'='*80}")
    print(f"ESTRAZIONE LINK OSHA (LISTA PRINCIPALE, ORDINATA PER DATA)")
    print(f"{'='*80}")
    print(f"URL base: {search_url}")
    print(f"Range: pagina {start_page} → {end_page}")
    print(f"{'='*80}\n")

    session = requests.Session()
    headers = {'User-Agent': OSHAConfig.USER_AGENT}
    session.headers.update(headers)

    actual_end = min(end_page, start_page + max_pages - 1) if max_pages else end_page

    for page_num in range(start_page, actual_end + 1):
        # URL con paginazione
        if page_num == 0:
            url = search_url
        else:
            separator = '&' if '?' in search_url else '?'
            url = f"{search_url}{separator}page={page_num}"

        print(f"[Pagina {page_num + 1}] Fetching: {url}")

        # Delay progressivo
        if page_num > start_page:
            delay = 5 + (page_num - start_page) * 2
            print(f"  [~] Attesa {delay} secondi...")
            time.sleep(delay)

        try:
            response = session.get(url, timeout=30)

            if response.status_code == 403:
                print(f"  [!] 403 Forbidden - aumenta delay")
                print(f"  [INFO] Pubblicazioni raccolte: {len(publications)}")
                break

            response.raise_for_status()
            soup = BeautifulSoup(response.content, 'lxml')

            results_found = False
            page_pubs = []

            # TROVA IL CONTAINER DELLA LISTA PRINCIPALE
            view_content = soup.find('div', class_='view-content')  # Drupal views
            if not view_content:
                # Fallback: cerca sezione con "Publications available"
                pub_text = soup.find(string=re.compile(r'Publications available \(\d+\)'))
                if pub_text:
                    view_content = pub_text.find_parent(['div', 'section'])

            if view_content:
                print(f"  [+] Container trovato: {view_content.name}.{'.'.join(view_content.get('class', []))}")

                # METODO 1: Articles node--type-publication dentro container
                articles = view_content.find_all('article', class_='node--type-publication')
                if articles:
                    print(f"  [+] Metodo 1: {len(articles)} articles")
                    results_found = True

                    for article in articles:
                        title_link = article.find('h2', class_='node__title') or article.find('h2') or article.find('h3')
                        if title_link:
                            a_tag = title_link.find('a')
                            if a_tag and a_tag.get('href'):
                                href = a_tag['href']
                                if href.startswith('/'):
                                    full_url = f"https://osha.europa.eu{href}"
                                else:
                                    full_url = href

                                if full_url not in seen_urls:
                                    title = a_tag.text.strip()
                                    page_pubs.append({
                                        'titolo': title,
                                        'url': full_url
                                    })
                                    seen_urls.add(full_url)

                # METODO 2: Views-row dentro container
                if not results_found:
                    rows = view_content.find_all('div', class_='views-row')
                    pattern = re.compile(r'/en/publications/[a-z0-9-]+')

                    print(f"  [+] Metodo 2: {len(rows)} views-row")
                    results_found = bool(rows)

                    for row in rows:
                        a_tag = row.find('a', href=pattern)
                        if a_tag:
                            href = a_tag['href']
                            if href.startswith('/'):
                                full_url = f"https://osha.europa.eu{href}"
                            else:
                                full_url = href

                            if full_url not in seen_urls:
                                title = a_tag.text.strip()
                                if len(title) < 5:  # Ridotto threshold
                                    heading = row.find(['h2', 'h3'])
                                    if heading:
                                        title = heading.text.strip()

                                if title and len(title) >= 5:
                                    page_pubs.append({
                                        'titolo': title,
                                        'url': full_url
                                    })
                                    seen_urls.add(full_url)

                # METODO 3: Headings con links dentro container
                if not results_found or not page_pubs:
                    pattern = re.compile(r'/en/publications/[a-z0-9-]+')
                    headings = view_content.find_all(['h2', 'h3'])  # Cerca headings
                    print(f"  [+] Metodo 3: {len(headings)} headings in view_content")

                    for heading in headings:
                        a_tag = heading.find('a', href=pattern)
                        if a_tag:
                            href = a_tag['href']
                            if href.startswith('/'):
                                full_url = f"https://osha.europa.eu{href}"
                            else:
                                full_url = href

                            if full_url not in seen_urls:
                                title = a_tag.text.strip()
                                if title:  # Rimuovi check len, titles sono lunghi
                                    page_pubs.append({
                                        'titolo': title,
                                        'url': full_url
                                    })
                                    seen_urls.add(full_url)

                    if page_pubs:
                        results_found = True
                        print(f"  [+] Trovati {len(page_pubs)} via headings")

            if not results_found:
                print(f"  [!] Nessun risultato nella lista principale - fallback globale")
                # Fallback: tutti links con pattern nel soup (esclude raccomandate manualmente se noto)
                pattern = re.compile(r'/en/publications/[a-z0-9-]+')
                all_links = soup.find_all('a', href=pattern)
                print(f"  [FALLBACK] {len(all_links)} link totali")
                for a in all_links[:3]:
                    print(f"    Debug: {a['href']} - '{a.text.strip()}' (len: {len(a.text.strip())})")
                # Filtra escludendo se text == 'See more' o short
                for a in all_links:
                    title = a.text.strip()
                    if len(title) > 10 and 'see more' not in title.lower():
                        full_url = f"https://osha.europa.eu{a['href']}" if a['href'].startswith('/') else a['href']
                        if full_url not in seen_urls:
                            page_pubs.append({'titolo': title, 'url': full_url})
                            seen_urls.add(full_url)
                if page_pubs:
                    results_found = True

            if page_pubs:
                print(f"  [FOUND] {len(page_pubs)} nuove pubblicazioni dalla lista principale")
                for pub in page_pubs:
                    print(f"    - {pub['titolo'][:75]}...")
                publications.extend(page_pubs)
            else:
                print(f"  [!] Ancora 0 - verifica manualmente")
                break  # Break solo se 0 (non <5)

        except requests.exceptions.RequestException as e:
            print(f"  [!] Errore: {e}")
            break

    print(f"\n[RESULT] Totale: {len(publications)} pubblicazioni trovate dalla lista principale")
    return publications

# PDF PROCESSING

def download_pdf_osha(pdf_url: str, output_path: Path) -> bool:

    # Scarica PDF da URL
    try:
        headers = {'User-Agent': OSHAConfig.USER_AGENT}
        response = requests.get(
            pdf_url,
            headers=headers,
            timeout=OSHAConfig.TIMEOUT,
            stream=True
        )
        response.raise_for_status()

        with open(output_path, 'wb') as f:
            for chunk in response.iter_content(chunk_size=8192):
                f.write(chunk)

        return output_path.exists() and output_path.stat().st_size > 0
    except Exception as e:
        print(f"[!] Errore download PDF: {e}")
        return False

