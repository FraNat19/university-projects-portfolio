# ENHANCED TABLE PARSER

def extract_table_metadata_enhanced(table_lines: List[str], context_lines: List[str]) -> Dict[str, Any]:

    # Estrae metadati avanzati da tabelle Markdown con context awareness

    metadata = {
        'caption': 'N/A',
        'title': 'N/A',
        'headers': [],
        'rows': [],
        'num_rows': 0,
        'num_columns': 0,
        'content_type': 'unknown'
    }

    # 1) CERCA CAPTION/TITOLO nelle linee precedenti
    descriptive_line = None  # FIX: Inizializza per evitare UnboundLocalError
    for line in reversed(context_lines[-10:]):
        clean = line.strip()
        if not clean or clean.startswith('#'):
            continue

        # Pattern per caption
        caption_patterns = [
            r'(?i)^(?:table|tabella|tab\.|tbl\.?)\s*\d*[\.:]\s*(.+)',
            r'(?i)^(?:table|tabella)\s+\d+[\s\-–—]+(.+)',
            r'(?i)^caption[\s:]+(.+)'
        ]

        for pattern in caption_patterns:
            match = re.search(pattern, clean)
            if match:
                metadata['caption'] = match.group(1).strip()
                metadata['title'] = clean
                break

        if metadata['caption'] != 'N/A':
            break

        # FIX: Check descrittivo DENTRO loop (usa ultima line valida)
        if len(clean) > 20 and not re.match(r'^[\|\-\s]+$', clean):
            descriptive_line = clean

    # Fallback caption da descriptive_line
    if metadata['caption'] == 'N/A' and descriptive_line:
        metadata['caption'] = descriptive_line[:150]

    # 2) ESTRAI HEADERS
    header_row = None
    separator_idx = -1

    for idx, line in enumerate(table_lines):
        if re.match(r'^\s*\|[\s\-\|:]+\|\s*$', line):
            separator_idx = idx
            if idx > 0:
                header_row = table_lines[idx - 1]
            break

    if header_row:
        headers_raw = [cell.strip() for cell in header_row.split('|') if cell.strip()]
        # FIX: Skip se è solo trattini (es. "|----|")
        metadata['headers'] = [h for h in headers_raw if h and not re.match(r'^[\-\s\|]+$', h)]
        metadata['num_columns'] = len(metadata['headers'])
    else:
        # Fallback senza separatore
        if len(table_lines) >= 2:
            first_row = table_lines[0]
            headers_raw = [cell.strip() for cell in first_row.split('|') if cell.strip() and len(cell.strip()) > 0 and not re.match(r'^[\-\s\|]+$', cell.strip())]
            if len(headers_raw) >= 2:
                metadata['headers'] = headers_raw[:2]
                metadata['num_columns'] = len(metadata['headers'])

    # 3) ESTRAI ROWS (skip celle vuote consecutive)
    if separator_idx >= 0:
        data_rows = table_lines[separator_idx + 1:]
    else:
        data_rows = table_lines[1:] if len(table_lines) > 1 and metadata['headers'] else table_lines

    for line in data_rows:
        if not line.strip() or re.match(r'^\s*[\|\-\s]+$', line):
            continue
        cells_raw = line.split('|')
        cells = [cell.strip() for cell in cells_raw if cell.strip()]  # Skip vuote
        if len(cells) >= 1:  # Almeno una cella non vuota
            # Pad con '' se < num_columns
            while len(cells) < metadata['num_columns']:
                cells.append('')
            metadata['rows'].append(cells[:metadata['num_columns']])  # Taglia extra

    metadata['num_rows'] = len(metadata['rows'])

    # 4) CONTENT TYPE (migliorato)
    if metadata['headers']:
        headers_text = ' '.join(metadata['headers']).lower()
        if any(kw in headers_text for kw in ['risk', 'hazard', 'danger', 'injury']):
            metadata['content_type'] = 'risk_assessment'
        elif any(kw in headers_text for kw in ['statistic', 'number', 'percentage', '%', 'rate']):
            metadata['content_type'] = 'statistical_data'
        elif any(kw in headers_text for kw in ['checklist', 'requirement', 'compliance']):
            metadata['content_type'] = 'compliance_checklist'
        elif any(kw in headers_text for kw in ['dx', 'a1', 'a2', 'read out', 'multiple answers']):
            metadata['content_type'] = 'survey_questionnaire'  # NUOVO per table_41

    if metadata['content_type'] == 'unknown' and metadata['rows']:
        rows_text = ' '.join(' '.join(row).lower() for row in metadata['rows'])
        if any(kw in rows_text for kw in ['website', 'period', 'data source', 'years', 'covered by']):
            metadata['content_type'] = 'data_source_metadata'
        elif any(kw in rows_text for kw in ['workload', 'harassment', 'bullying', 'digital technologies', 'automation', 'emotional burden']):
            metadata['content_type'] = 'psychosocial_risks'  # NUOVO per table_1
        else:
            metadata['content_type'] = 'general_data'

    return metadata

def format_table_content_readable(metadata: Dict[str, Any]) -> str:

    # Formatta contenuto tabella in modo leggibile
    lines = []

    if metadata['headers']:
        header_line = ' | '.join([h if h else '' for h in metadata['headers']])  # Gestisci empty
        lines.append(header_line)
        lines.append('-' * len(header_line))

    for row in metadata['rows']:
        if metadata['headers']:
            padded_cells = []
            for i, cell in enumerate(row):
                cell_str = str(cell)
                if re.match(r'^https?://', cell_str):
                    max_len = 1000
                else:
                    max_len = 500
                cell_str = cell_str[:max_len]
                header_len = len(metadata['headers'][i]) if i < len(metadata['headers']) and metadata['headers'][i] else len(cell_str)
                padded_cells.append(cell_str.ljust(header_len))
            lines.append(' | '.join(padded_cells))
        else:
            lines.append(' • ' + ' | '.join(str(c)[:500] for c in row))

    return '\n'.join(lines)

# DOCUMENT STRUCTURE ANALYSIS

def analyze_document_structure_enhanced(doc) -> Dict[str, Any]:

    # Analizza struttura documento con ENHANCED TABLE PARSING
    structure = {
        'num_tables': 0,
        'num_figures': 0,
        'num_headings': 0,
        'headings': [],
        'tables': [],
        'figures': []
    }

    try:
        markdown = doc.export_to_markdown()
        lines = markdown.split('\n')

        # 1) HEADINGS (invariato)
        for i, line in enumerate(lines):
            if line.strip().startswith('#'):
                level = len(line) - len(line.lstrip('#'))
                text = line.lstrip('#').strip()
                structure['num_headings'] += 1
                structure['headings'].append({
                    'type': f'heading_level_{level}',
                    'text': text[:200],
                    'position': i,
                    'level': level
                })

        # 2) TABLES - ENHANCED PARSING
        in_table = False
        current_table_lines = []
        table_start_idx = -1

        for i, line in enumerate(lines):
            # Identifica inizio tabella
            if '|' in line and ('-' in line or '─' in line or ':' in line):
                if not in_table:
                    in_table = True
                    table_start_idx = i
                    current_table_lines = []

            if in_table:
                if '|' in line:
                    current_table_lines.append(line)
                else:
                    # Fine tabella
                    if current_table_lines and len(current_table_lines) >= 2:
                        # Estrai context (linee prima della tabella)
                        context_start = max(0, table_start_idx - 15)
                        context_lines = lines[context_start:table_start_idx]

                        # ENHANCED PARSING
                        metadata = extract_table_metadata_enhanced(
                            current_table_lines,
                            context_lines
                        )

                        # Formatta contenuto
                        readable_content = format_table_content_readable(metadata)

                        structure['num_tables'] += 1
                        structure['tables'].append({
                            'table_id': f'table_{structure["num_tables"]}',
                            'caption': metadata['caption'],
                            'title': metadata['title'],
                            'text_content': readable_content,
                            'raw_markdown': '\n'.join(current_table_lines),
                            'num_rows': metadata['num_rows'],
                            'num_columns': metadata['num_columns'],
                            'potential_columns': metadata['headers'],
                            'content_type': metadata['content_type'],
                            'position': table_start_idx,
                            'enhanced_parsing': True
                        })

                    in_table = False
                    current_table_lines = []

        # Gestisci tabella che termina a fine documento
        if in_table and current_table_lines and len(current_table_lines) >= 2:
            context_start = max(0, table_start_idx - 15)
            context_lines = lines[context_start:table_start_idx]

            metadata = extract_table_metadata_enhanced(current_table_lines, context_lines)
            readable_content = format_table_content_readable(metadata)

            structure['num_tables'] += 1
            structure['tables'].append({
                'table_id': f'table_{structure["num_tables"]}',
                'caption': metadata['caption'],
                'title': metadata['title'],
                'text_content': readable_content,
                'raw_markdown': '\n'.join(current_table_lines),
                'num_rows': metadata['num_rows'],
                'num_columns': metadata['num_columns'],
                'potential_columns': metadata['headers'],
                'content_type': metadata['content_type'],
                'position': table_start_idx,
                'enhanced_parsing': True
            })

        # 3) FIGURES
        for i, line in enumerate(lines):
            if '<!-- image -->' in line.lower() or (line.strip().startswith('![') and '](' in line):
                structure['num_figures'] += 1
                caption = 'N/A'
                for j in range(i+1, min(len(lines), i+5)):
                    candidate = lines[j].strip()
                    if candidate and not candidate.startswith('#'):
                        caption = candidate
                        break

                structure['figures'].append({
                    'figure_id': f'figure_{structure["num_figures"]}',
                    'caption': caption,
                    'position': i,
                    'vlm_description': None
                })

    except Exception as e:
        print(f"[!] Errore analisi: {e}")

    return structure

# EXPORT TABLES

def export_tables_to_files_enhanced(tables: List[Dict], doc_id: str, tables_dir: Path) -> List[str]:

    # Esporta tabelle con METADATI ARRICCHITI
    if not tables:
        return []

    doc_tables_dir = tables_dir / doc_id
    doc_tables_dir.mkdir(parents=True, exist_ok=True)
    exported_tables = []

    for table in tables:
        table_id = table['table_id']
        txt_path = doc_tables_dir / f"{table_id}.txt"

        try:
            with open(txt_path, 'w', encoding='utf-8') as f:
                f.write("="*80 + "\n")
                f.write(f"TABELLA: {table_id}")
                if table.get('enhanced_parsing'):
                    f.write(" (Enhanced Parsing)")
                f.write("\n" + "="*80 + "\n\n")

                # METADATI ARRICCHITI
                f.write(" METADATI TABELLA\n")
                f.write("-"*80 + "\n")
                f.write(f"Titolo/Caption: {table.get('title', 'N/A')}\n")
                f.write(f"Caption estratta: {table.get('caption', 'N/A')}\n")
                f.write(f"Tipo contenuto: {table.get('content_type', 'N/A')}\n")
                f.write(f"Righe dati: {table.get('num_rows', 'N/A')}\n")
                f.write(f"Colonne: {table.get('num_columns', len(table.get('potential_columns', [])))}\n")
                f.write(f"Posizione nel documento: {table.get('position', 'N/A')}\n")
                f.write("\n")

                # HEADERS/COLONNE
                if table.get('potential_columns'):
                    f.write(" COLONNE IDENTIFICATE:\n")
                    for idx, col in enumerate(table['potential_columns'], 1):
                        f.write(f" {idx}. {col}\n")
                    f.write("\n")

                # CONTENUTO PULITO
                f.write(" CONTENUTO (formattato):\n")
                f.write("-"*80 + "\n")
                f.write(table['text_content'])
                f.write("\n" + "-"*80 + "\n\n")

                # RAW MARKDOWN (per debug)
                if table.get('raw_markdown'):
                    f.write(" MARKDOWN ORIGINALE (debug):\n")
                    f.write("-"*80 + "\n")
                    f.write(table['raw_markdown'])
                    f.write("\n" + "-"*80 + "\n")

            exported_tables.append(str(txt_path))
            print(f" [+] {txt_path.name} ({' enhanced' if table.get('enhanced_parsing') else 'standard'})")
        except Exception as e:
            print(f" [!] Errore export tabella {table_id}: {e}")

    return exported_tables

